using System.Text;
using Haldus.Generators.Infrastructure;
using Haldus.Generators.Model;

namespace Haldus.Generators.Emit;

/// <summary>Modülün (assembly'nin) kayıt kodunu ve bağlamın DbSet özelliklerini üretir.</summary>
internal static class ModuleEmitter
{
    public static string EmitModule(IReadOnlyList<(ResourceModel Resource, string Namespace)> resources)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Haldus.Generated;");
        builder.AppendLine();
        builder.AppendLine("internal static class HaldusModule");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("    internal static void Initialize()");
        builder.AppendLine("    {");
        builder.AppendLine("        global::Haldus.HaldusModelRegistry.Register(typeof(HaldusModule).Assembly, static modelBuilder =>");
        builder.AppendLine("        {");

        foreach (var (resource, entityNamespace) in resources)
        {
            builder.AppendLine($"            modelBuilder.Entity<{ResourceEmitter.QualifiedName(resource, entityNamespace)}>();");
        }

        builder.AppendLine("        });");

        foreach (var (resource, entityNamespace) in resources)
        {
            var entity = ResourceEmitter.QualifiedName(resource, entityNamespace);
            builder.AppendLine();
            builder.AppendLine($"        global::Haldus.HaldusEndpointRegistry.Register<{entity}>({entity}Endpoints.Map);");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>Eklenecek DbSet yoksa <c>null</c> döner.</summary>
    public static string? EmitDbContext(DbContextModel dbContext, IReadOnlyList<(ResourceModel Resource, string Namespace)> resources)
    {
        var existing = new HashSet<string>(dbContext.MemberNames);
        var builder = new StringBuilder();

        foreach (var (resource, entityNamespace) in resources)
        {
            var setName = Naming.Pluralize(resource.EntityName);
            if (!existing.Add(setName))
            {
                continue;
            }

            var entity = ResourceEmitter.QualifiedName(resource, entityNamespace);
            builder.AppendLine($"    public global::Microsoft.EntityFrameworkCore.DbSet<{entity}> {setName} => Set<{entity}>();");
        }

        if (builder.Length == 0)
        {
            return null;
        }

        var namespaceLine = dbContext.Namespace.Length == 0 ? string.Empty : $"namespace {dbContext.Namespace};";

        return $$"""
            // <auto-generated/>
            #nullable enable

            {{namespaceLine}}

            partial class {{dbContext.Name}}
            {
            {{builder.ToString().TrimEnd()}}
            }

            """;
    }
}
