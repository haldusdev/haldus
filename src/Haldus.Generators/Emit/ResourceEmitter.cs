using System.Text;
using Haldus.Generators.Model;

namespace Haldus.Generators.Emit;

/// <summary>Bir kaynağın entity yarısını ve DTO'larını üretir.</summary>
internal static class ResourceEmitter
{
    public const string Header = "// <auto-generated/>\n#nullable enable\n";

    private const string RequiredAttributeName = "global::System.ComponentModel.DataAnnotations.RequiredAttribute";
    private const string MaxLength = "global::System.ComponentModel.DataAnnotations.MaxLengthAttribute";
    private const string NotNullWhenSetAttributeName = "global::Haldus.NotNullWhenSetAttribute";

    public static string QualifiedName(ResourceModel resource, string entityNamespace) =>
        entityNamespace.Length == 0
            ? $"global::{resource.EntityName}"
            : $"global::{entityNamespace}.{resource.EntityName}";

    public static string NamespaceLine(string entityNamespace) =>
        entityNamespace.Length == 0 ? string.Empty : $"namespace {entityNamespace};\n";

    /// <summary>Üretilecek bir şey yoksa (kullanıcı Id'yi yazdıysa ve trait yoksa) <c>null</c> döner.</summary>
    public static string? EmitEntity(ResourceModel resource, string entityNamespace)
    {
        var declared = new HashSet<string>(resource.DeclaredTraitMembers);
        var interfaces = new List<string>();
        var members = new List<string>();

        if (!resource.IdDeclared && resource.KeyName.Length > 0)
        {
            members.Add(resource.IdKind == IdKind.String
                ? $"    [{MaxLength}(200)]\n    public string {resource.KeyName} {{ get; set; }} = \"\";"
                : $"    public {resource.IdType} {resource.KeyName} {{ get; set; }}");
        }

        // Archetype'ın kendi eklediği alanlar (ör. Lookup'ın Name alanı).
        foreach (var property in resource.Properties.Where(property => property.IsGenerated))
        {
            var attributes = string.Concat(property.ValidationAttributes.Select(attribute => $"    [{attribute.Rendered}]\n"));
            members.Add($"{attributes}    public {property.Type} {property.Name} {{ get; set; }} = \"\";");
        }

        foreach (var trait in TraitCatalog.For(resource.Traits))
        {
            interfaces.Add(trait.Interface);
            members.AddRange(trait.Members
                .Where(member => !declared.Contains(member.Name))
                .Select(member => $"    public {member.Type} {member.Name} {{ get; set; }}"));
        }

        if (interfaces.Count == 0 && members.Count == 0)
        {
            return null;
        }

        // Kullanıcı sınıfı yazdıysa erişim belirleyicisi onun bildiriminden gelir.
        var accessibility = resource.EntityDeclared ? string.Empty : "public ";
        var baseList = interfaces.Count == 0 ? string.Empty : " : " + string.Join(", ", interfaces);

        var builder = new StringBuilder();
        builder.Append(Header).Append('\n');
        builder.Append(NamespaceLine(entityNamespace)).Append('\n');
        builder.Append($"{accessibility}partial class {resource.EntityName}{baseList}\n");
        builder.Append("{\n");
        builder.Append(string.Join("\n\n", members)).Append('\n');
        builder.Append("}\n");

        return builder.ToString();
    }

    public static string EmitDtos(ResourceModel resource, string entityNamespace)
    {
        var builder = new StringBuilder();
        builder.Append(Header).Append('\n');
        builder.Append(NamespaceLine(entityNamespace));

        builder.Append('\n');
        builder.Append($"public sealed partial record {resource.EntityName}Response\n");
        builder.Append("{\n");
        if (resource.KeyName.Length > 0)
        {
            builder.Append($"    public required {resource.IdType} {resource.KeyName} {{ get; init; }}\n");
        }

        foreach (var property in resource.Properties)
        {
            builder.Append($"    public required {property.Type} {property.Name} {{ get; init; }}\n");
        }

        foreach (var member in TraitCatalog.ResponseMembers(resource.Traits))
        {
            builder.Append($"    public required {member.Type} {member.Name} {{ get; init; }}\n");
        }

        builder.Append("}\n");

        if (resource.Has(Operations.Create))
        {
            AppendRequest(builder, $"Create{resource.EntityName}Request", resource);
        }

        if (resource.Has(Operations.Update))
        {
            AppendRequest(builder, $"{WriteOperationName(resource)}{resource.EntityName}Request", resource);
        }

        if (resource.Has(Operations.Patch))
        {
            AppendPatchRequest(builder, resource);
        }

        if (resource.SearchFields.Length > 0)
        {
            AppendSearchTypes(builder, resource);
        }

        return builder.ToString();
    }

    public static string ConditionType(SearchField field) => field.Kind switch
    {
        SearchKind.String => "global::Haldus.StringCondition",
        SearchKind.Range => $"global::Haldus.RangeCondition<{field.ValueType}>",
        _ => $"global::Haldus.EqualityCondition<{field.ValueType}>",
    };

    public static string CamelCase(string name) => char.ToLowerInvariant(name[0]) + name.Substring(1);

    /// <summary>Anahtarı istemcinin verdiği archetype'larda PUT ekle-veya-güncelle anlamına gelir ve adı da öyledir.</summary>
    public static string WriteOperationName(ResourceModel resource) => resource.Archetype.HasClientKey() ? "Put" : "Update";

    /// <summary>
    /// Arama gövdesinin tipleri. Yalnızca <c>.Searchable(...)</c> ile sayılan alanlar koşul ve sıralama
    /// alanı olur; sıralama alanı enum olduğu için bilinmeyen bir ad istek okunurken reddedilir.
    /// </summary>
    private static void AppendSearchTypes(StringBuilder builder, ResourceModel resource)
    {
        const string Json = "global::System.Text.Json.Serialization";
        const string List = "global::System.Collections.Generic.IReadOnlyList";
        var entity = resource.EntityName;

        // Bilinmeyen bir alan adı sessizce yok sayılırsa yanlış yazılmış bir koşul süzülmemiş sonuç döndürür.
        var strict = $"[{Json}.JsonUnmappedMemberHandling({Json}.JsonUnmappedMemberHandling.Disallow)]\n";

        builder.Append('\n');
        builder.Append(strict);
        builder.Append($"public sealed partial record {entity}Where\n");
        builder.Append("{\n");

        foreach (var field in resource.SearchFields)
        {
            builder.Append($"    public {ConditionType(field)}? {field.Name} {{ get; init; }}\n\n");
        }

        builder.Append($"    public {List}<{entity}Where>? And {{ get; init; }}\n\n");
        builder.Append($"    public {List}<{entity}Where>? Or {{ get; init; }}\n\n");
        builder.Append($"    public {entity}Where? Not {{ get; init; }}\n");
        builder.Append("}\n");

        builder.Append('\n');
        builder.Append($"[{Json}.JsonConverter(typeof({Json}.JsonStringEnumConverter<{entity}SearchField>))]\n");
        builder.Append($"public enum {entity}SearchField\n");
        builder.Append("{\n");

        foreach (var field in resource.SearchFields)
        {
            builder.Append($"    [{Json}.JsonStringEnumMemberName(\"{CamelCase(field.Name)}\")]\n");
            builder.Append($"    {field.Name},\n");
        }

        builder.Append("}\n");

        builder.Append('\n');
        builder.Append(strict);
        builder.Append($"public sealed partial record {entity}Sort\n");
        builder.Append("{\n");
        builder.Append($"    public required {entity}SearchField Field {{ get; init; }}\n\n");
        builder.Append("    public bool Descending { get; init; }\n");
        builder.Append("}\n");

        builder.Append('\n');
        builder.Append(strict);
        builder.Append($"public sealed partial record {entity}SearchRequest\n");
        builder.Append("{\n");
        builder.Append($"    public {entity}Where? Where {{ get; init; }}\n\n");
        builder.Append($"    public {List}<{entity}Sort>? Sort {{ get; init; }}\n\n");
        builder.Append("    public int? Page { get; init; }\n\n");
        builder.Append("    public int? PageSize { get; init; }\n");

        if (resource.Has(Traits.SoftDeletable))
        {
            builder.Append("\n    public bool? IncludeDeleted { get; init; }\n");
        }

        if (resource.Has(Traits.Archivable))
        {
            builder.Append("\n    public bool? IncludeArchived { get; init; }\n");
        }

        builder.Append("}\n");
    }

    private static void AppendRequest(StringBuilder builder, string name, ResourceModel resource)
    {
        builder.Append('\n');
        builder.Append($"public sealed partial record {name}\n");
        builder.Append("{\n");

        var first = true;
        foreach (var property in resource.Properties.Where(property => property.IsWritable))
        {
            if (!first)
            {
                builder.Append('\n');
            }

            first = false;

            foreach (var attribute in property.ValidationAttributes)
            {
                builder.Append($"    [{attribute.Rendered}]\n");
            }

            var initializer = property.IsNonNullableReference ? " = default!;" : string.Empty;
            builder.Append($"    public {property.Type} {property.Name} {{ get; init; }}{initializer}\n");
        }

        builder.Append("}\n");
    }

    /// <summary>
    /// PATCH isteğinde her alan isteğe bağlıdır. "Gönderilmedi" ile "null gönderildi" ayrımı, init
    /// erişimcisinin yalnızca JSON'da bulunan alanlar için çağrılmasına dayanır; böylece şemada sarmalayıcı
    /// bir tip görünmez.
    /// </summary>
    private static void AppendPatchRequest(StringBuilder builder, ResourceModel resource)
    {
        var writable = resource.Properties.Where(property => property.IsWritable).ToArray();

        builder.Append('\n');
        builder.Append($"public sealed partial record Patch{resource.EntityName}Request : global::Haldus.IHaldusPatch\n");
        builder.Append("{\n");

        foreach (var property in writable)
        {
            builder.Append($"    private readonly {property.NullableType} {FieldName(property)};\n");
            builder.Append($"    private readonly bool {FieldName(property)}Set;\n");
        }

        foreach (var property in writable)
        {
            builder.Append('\n');

            var required = property.ValidationAttributes.FirstOrDefault(attribute => attribute.IsRequired);
            if (required is not null)
            {
                // Required'ın argümanları (AllowEmptyStrings, ErrorMessage...) aynen taşınır; böylece PATCH,
                // PUT ve POST'un reddettiği bir değeri kabul etmez.
                builder.Append($"    [{NotNullWhenSetAttributeName}{required.Rendered.Substring(RequiredAttributeName.Length)}]\n");
            }
            else if (property.IsNonNullable)
            {
                builder.Append($"    [{NotNullWhenSetAttributeName}(AllowEmptyStrings = true)]\n");
            }

            foreach (var attribute in property.ValidationAttributes.Where(attribute => !attribute.IsRequired))
            {
                builder.Append($"    [{attribute.Rendered}]\n");
            }

            builder.Append($"    public {property.NullableType} {property.Name}\n");
            builder.Append("    {\n");
            builder.Append($"        get => {FieldName(property)};\n");
            builder.Append("        init\n");
            builder.Append("        {\n");
            builder.Append($"            {FieldName(property)} = value;\n");
            builder.Append($"            {FieldName(property)}Set = true;\n");
            builder.Append("        }\n");
            builder.Append("    }\n");
        }

        if (writable.Length > 0)
        {
            builder.Append('\n');
        }

        builder.Append("    bool global::Haldus.IHaldusPatch.IsSet(string propertyName) => propertyName switch\n");
        builder.Append("    {\n");

        foreach (var property in writable)
        {
            builder.Append($"        \"{property.Name}\" => {FieldName(property)}Set,\n");
        }

        builder.Append("        _ => false,\n");
        builder.Append("    };\n");
        builder.Append("}\n");
    }

    private static string FieldName(PropertyModel property) =>
        "_" + char.ToLowerInvariant(property.Name[0]) + property.Name.Substring(1);
}
